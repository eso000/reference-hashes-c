#!/bin/sh

# Regenerate tests/boundary_vectors.h with the checksum tools that ship with
# GNU coreutils. Every vector is the digest of a message of the given length
# filled with the byte in the second field.
set -eu

cd "$(dirname "$0")/.."

LENGTHS="0 1 2 3 7 8 15 16 55 56 57 63 64 65 111 112 113 119 120 121 127 128 129 191 192 193 255 256 257 1000"
# Fill bytes in hex: 'a', 0x00, 0xff and 0x80. The high-bit fills make sure
# the word-loading code is exercised with bytes that do not fit in a signed
# char, and 0x00/0xff cover the all-zero and all-ones extremes.
PATTERNS="61 00 ff 80"
ALGS="md5 sha1 sha224 sha256 sha384 sha512"
OUT="tests/boundary_vectors.h"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

for alg in $ALGS; do
  if ! command -v "${alg}sum" >/dev/null 2>&1; then
    echo "missing ${alg}sum (GNU coreutils)" >&2
    exit 1
  fi
done

fill_message() { # length hex-fill-byte
  if [ "$2" = "00" ]; then
    head -c "$1" /dev/zero > "$TMP"
  else
    oct=$(printf '%03o' "0x$2")
    head -c "$1" /dev/zero | tr '\000' "\\$oct" > "$TMP"
  fi
}

{
  printf '/* Generated by tests/gen_vectors.sh with %s.\n' "$(md5sum --version | head -n 1)"
  printf ' * Messages are filled with the byte in the second field.\n'
  printf ' * Do not edit by hand. */\n'
  printf '#ifndef HASH_BOUNDARY_VECTORS_H\n'
  printf '#define HASH_BOUNDARY_VECTORS_H\n\n'

  for alg in $ALGS; do
    printf 'static const boundary_vector %s_boundary[] = {\n' "$alg"
    for fill in $PATTERNS; do
      for len in $LENGTHS; do
        fill_message "$len" "$fill"
        hex="$("${alg}sum" "$TMP" | cut -d ' ' -f 1)"
        printf '  {%d, 0x%s, "%s"},\n' "$len" "$fill" "$hex"
      done
    done
    printf '};\n\n'
  done

  printf '#endif\n'
} > "$OUT"

echo "wrote $OUT"
